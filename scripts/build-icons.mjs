// Regenerates src/components/Icon/icons.ts from the SVG exports in src/assets/icons.
// Strokes and fills are switched to currentColor (masks and clip paths are left alone)
// and internal ids are prefixed per icon so several icons can share a page.
// A file named <name>.color.svg keeps its own colors (for multi-color marks).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "src/assets/icons";
const OUT = "src/components/Icon/icons.ts";

function convert(name, svg, keepColors) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  const refs = new Set([...body.matchAll(/(?:url\(#|href="#)([^)"]+)/g)].map((m) => m[1]));
  body = body.replace(/\s+id="([^"]*)"/g, (m, id) => (refs.has(id) ? m : ""));
  // Recolor everything outside <mask>, <clipPath> and <defs>.
  body = body
    .split(/(<(?:mask|clipPath|defs)\b[\s\S]*?<\/(?:mask|clipPath|defs)>)/)
    .map((part, i) =>
      i % 2 === 1 || keepColors
        ? part
        : part
            .replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"')
            .replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"'),
    )
    .join("");
  for (const ref of refs) {
    const id = `axo-${name}-${ref}`;
    body = body.split(`"${ref}"`).join(`"${id}"`).split(`#${ref})`).join(`#${id})`).split(`"#${ref}"`).join(`"#${id}"`);
  }
  body = body.replace(/xlink:href/g, "href").replace(/\s+/g, " ").replace(/> </g, "><");
  return { viewBox, body };
}

const files = readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort();
const lines = [
  "/* Icons used by the components, copied from the Icon page of the Figma file.",
  "   Generated by scripts/build-icons.mjs from src/assets/icons; run `npm run icons` after adding an SVG. */",
  "",
  "export const icons = {",
];
for (const file of files) {
  const keepColors = file.endsWith(".color.svg");
  const name = file.replace(/(\.color)?\.svg$/, "");
  const { viewBox, body } = convert(name, readFileSync(join(SRC, file), "utf8"), keepColors);
  lines.push(`  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`);
}
lines.push("} as const;", "", "export type IconName = keyof typeof icons;", "");
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${files.length} icons to ${OUT}`);
